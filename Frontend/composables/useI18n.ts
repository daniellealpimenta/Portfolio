export type MessageKey = keyof typeof messages.pt

export function useI18n() {
  const { lang, toggleLang } = useLanguage()
  const t = (key: MessageKey) => messages[lang.value][key] ?? messages.pt[key] ?? key
  const locale = computed(() => (lang.value === 'en' ? 'en-US' : 'pt-BR'))
  return { t, lang, locale, toggleLang }
}
